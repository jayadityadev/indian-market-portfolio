# src/api/routes/benchmark.py
"""Benchmark API route — GET /benchmark.
Returns a JSON payload comparing the performance of the XGBoost classifier
against the LSTM‑DNN benchmark model across several risk‑adjusted metrics.
The actual training of the LSTM model is performed elsewhere (see `src/models/lstm_dnn.py`).
This endpoint simply loads the persisted results and formats them for the client.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict

from fastapi import APIRouter, BackgroundTasks, HTTPException

from db.service import save_benchmark_record

router = APIRouter()

# Path to stored benchmark results (generated by the ML pipeline)
PROJECT_ROOT = Path(__file__).resolve().parents[3]
BENCHMARK_FILE = PROJECT_ROOT / "data" / "benchmark_results.json"

@router.get("/benchmark", summary="Model benchmark comparison", tags=["Benchmark"])
def get_benchmark(background_tasks: BackgroundTasks) -> Dict[str, Any]:
    """Return a dictionary with XGBoost vs LSTM performance metrics.

    The JSON file is expected to contain a structure like:
    {
        "xgboost": {"CAGR": 0.12, "Sharpe": 1.4, ...},
        "lstm":    {"CAGR": 0.09, "Sharpe": 1.1, ...}
    }
    If the file is missing we raise a 500 error – the upstream pipeline should
    generate it before the endpoint is used.
    """
    if not BENCHMARK_FILE.exists():
        raise HTTPException(status_code=500, detail="Benchmark results not found.")
    try:
        with open(BENCHMARK_FILE, "r", encoding="utf-8") as f:
            data = json.load(f)
        provenance = data.get("data_provenance", {})
        models = []
        for name, key in (("XGBoost", "xgboost_metrics"), ("LSTM-DNN", "lstm_metrics")):
            metrics = data.get(key, {})
            if isinstance(metrics, dict):
                models.append(
                    {
                        "model_name": name,
                        "accuracy": metrics.get("accuracy", 0.0),
                        "precision": metrics.get("precision"),
                        "recall": metrics.get("recall"),
                        "f1_score": metrics.get("f1_score", 0.0),
                        "training_time_sec": metrics.get("training_time_sec"),
                        "architecture_summary": data.get("model_architecture", ""),
                        "details": {
                            "data_provenance": provenance,
                            "overfitting_gap": data.get("overfitting_gap", {}),
                            "latency": data.get("latency_benchmark", {}).get(name.lower(), {}),
                        },
                    }
                )
        if models:
            background_tasks.add_task(
                save_benchmark_record,
                {
                    "ticker": provenance.get("ticker", "^NSEI"),
                    "evaluation_date": provenance.get("end", ""),
                    "models": models,
                },
            )
        return data
    except Exception as exc:
        raise HTTPException(status_code=500, detail=f"Failed to read benchmark file: {exc}")
